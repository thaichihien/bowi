// @vitest-environment happy-dom
import { render } from 'preact';
import { act } from 'preact/test-utils';
import { beforeAll, beforeEach, describe, expect, it } from 'vitest';
import type { ReviewPlan } from '@bowi/core';
import { renderMarkdown } from '../src/markdown.ts';
import { App } from '../ui/App.tsx';
import { fixturePlan } from './plan.ts';

let local: ReviewPlan;
let pr: ReviewPlan;
let root: HTMLElement;
const NOW = Date.parse('2026-01-07T12:00:00Z');

beforeAll(async () => {
  ({ plan: local } = await fixturePlan());
  pr = structuredClone(local);
  Object.assign(pr.source, {
    kind: 'github',
    repo: 'acme/api',
    prNumber: 7,
    title: 'Send a verification email on register',
    author: 'octocat',
    createdAt: '2026-01-05T09:00:00Z',
    description: '## Summary\n\n- [x] Tests\n\n<img src="https://x/y.png" alt="screen">',
  });
  pr.source.descriptionHtml = renderMarkdown(pr.source.description!);
});

const show = (plan: ReviewPlan, hash = '') => {
  localStorage.clear(); // the diff layout is remembered per viewer
  window.location.hash = hash;
  document.body.innerHTML = '<div id="app"></div>';
  root = document.getElementById('app')!;
  render(<App plan={plan} now={NOW} />, root);
};

beforeEach(() => show(local));

const text = () => root.textContent ?? '';
const press = (el: Element | undefined | null) => act(() => (el as HTMLElement).click());
const buttons = () => [...root.querySelectorAll('button')];
const click = (label: string | RegExp) => {
  const b = buttons().find((x) =>
    typeof label === 'string' ? x.textContent?.trim() === label : label.test(x.textContent ?? ''),
  );
  if (!b)
    throw new Error(
      `No button ${label}: ${buttons()
        .map((x) => x.textContent)
        .join(' | ')}`,
    );
  return press(b);
};
const tab = (label: string) =>
  press([...root.querySelectorAll('.tab')].find((t) => t.textContent?.startsWith(label)));
const tabNames = () => [...root.querySelectorAll('.tab')].map((t) => t.textContent);

describe('header and tabs', () => {
  it('shows repo, title, commits, stats and the tabs for local changes (UI-2)', () => {
    expect(root.querySelector('.header-top')!.textContent).toMatch(
      /^ev · local changesGenerated by Bowi test · head [0-9a-f]{7}$/,
    );
    expect(root.querySelector('h1')!.textContent).toBe('feature/email-verification');
    expect(root.querySelectorAll('.meta-line')[0]!.textContent).toBe(
      '4 commits on feature/email-verification compared with main',
    );
    expect(text()).toContain('11 files changed');
    expect(text()).toContain('+115 −25');
    expect(text()).toContain('94 lines need careful reading');
    // No Description tab for local changes.
    expect(tabNames()).toEqual(['Review8 steps', 'Commits4', 'Changes11']);
  });

  it('describes a pull request and offers its description', () => {
    show(pr);
    expect(root.querySelector('.header-top')!.textContent).toContain('acme/api · pull request #7');
    expect(root.querySelector('h1')!.textContent).toBe('Send a verification email on register');
    expect(root.querySelectorAll('.meta-line')[0]!.textContent).toBe(
      'Merging 4 commits from feature/email-verification into main',
    );
    expect(tabNames()).toEqual(['Review8 steps', 'Description', 'Commits4', 'Changes11']);
  });

  it('keeps the tab in the URL hash, including old #alpha links', async () => {
    await tab('Commits');
    expect(window.location.hash).toBe('#commits');
    show(local, '#alpha');
    expect(root.querySelector('.tab.on')!.textContent).toBe('Changes11');
    show(local, '#g1:service');
    expect(root.querySelector('.step h3')!.textContent).toBe('Step 2 of 5 · Services');
    show(local, '#description'); // local changes have no description: back to Review
    expect(root.querySelector('.tab.on')!.textContent).toBe('Review8 steps');
  });
});

describe('Review tab', () => {
  it('shows the groups in order and the first step (UI-3)', () => {
    const groups = [...root.querySelectorAll('.grp .grp-title')].map((e) => e.textContent);
    expect(groups).toEqual([
      'New AuthService.verifyEmail() and 9 related changes',
      'Move slugify() from helpers.ts to string.ts',
      'Generated files and formatting',
    ]);
    expect(root.querySelector('.step h3')!.textContent).toBe('Step 1 of 5 · Data shape');
    expect(text()).toContain('0 of 8 steps reviewed');
  });

  it('gives every step an icon for its layer or noise kind', () => {
    const icons = [...root.querySelectorAll('.step-btn .sic')].map((e) => e.className);
    expect(icons).toEqual([
      'sic ic-data',
      'sic ic-service',
      'sic ic-api',
      'sic ic-test',
      'sic ic-docs',
      'sic ic-move',
      'sic ic-generated',
      'sic ic-format',
    ]);
  });

  it('keeps "why these changes are grouped" closed until asked (UI-4)', async () => {
    expect(text()).toContain('Why these changes are grouped6 links');
    expect(root.querySelector('.reasons ul')).toBeNull();
    await click(/^Why these changes are grouped/);
    expect(root.querySelectorAll('.reasons li')).toHaveLength(6);
  });

  it('opens and closes a file of the step', async () => {
    const head = root.querySelector('.file-head') as HTMLButtonElement;
    expect(head.getAttribute('aria-expanded')).toBe('true');
    const lines = root.querySelectorAll('.ln').length;
    await press(head);
    expect(head.getAttribute('aria-expanded')).toBe('false');
    expect(root.querySelectorAll('.ln').length).toBeLessThan(lines);
    expect(head.textContent).toMatch(/1 hunk · \d+ lines hidden/);
  });

  it('marks steps reviewed and moves to the next step (UI-11)', async () => {
    await click(/^Next: Services/);
    expect(root.querySelector('.step h3')!.textContent).toBe('Step 2 of 5 · Services');
    expect(text()).toContain('1 of 8 steps reviewed');
    await click('Mark as reviewed');
    expect(text()).toContain('2 of 8 steps reviewed');
    expect(root.querySelectorAll('.step-btn [aria-label="Reviewed"]')).toHaveLength(2);
    expect(window.location.hash).toBe('#g1:service');
  });

  it('switches to tests-first order (UI-10)', async () => {
    await click('Tests first');
    await click(/New AuthService.verifyEmail/);
    expect(root.querySelector('.step h3')!.textContent).toBe('Step 1 of 5 · Tests');
  });

  it('shows the moved code with the changed line and its original (UI-6)', async () => {
    await click(/slugify\(\) moved/);
    expect(root.querySelectorAll('.ln.l-x')).toHaveLength(1);
    expect(root.querySelector('.ln.l-x')!.textContent).toContain('[^\\w]+');
    expect(root.querySelector('.ln.l-w')!.textContent).toContain('[^a-z0-9]+');
    expect(root.querySelectorAll('.ln.l-m').length).toBeGreaterThan(4);
  });

  it('collapses noise behind a summary with a raw diff toggle (UI-7)', async () => {
    await click(/Generated filespackage-lock.json/);
    expect(text()).toContain('1 new direct dependency: nodemailer');
    expect(root.querySelectorAll('.ln')).toHaveLength(0);
    await click('Show raw diff');
    expect(root.querySelectorAll('.ln').length).toBeGreaterThan(0);
  });
});

describe('Description tab', () => {
  it('renders the sanitized description, images as links', async () => {
    show(pr, '#description');
    const md = root.querySelector('.md')!;
    expect(md.querySelector('h2')!.textContent).toBe('Summary');
    expect(md.querySelector('input[type="checkbox"]')!.hasAttribute('checked')).toBe(true);
    expect(md.querySelector('img')).toBeNull();
    expect(md.querySelector('a.md-image')!.textContent).toBe('Image: screen');
    expect(root.querySelector('.desc-head > span:last-child')!.textContent).toBe(
      'octocat opened this pull request 2 days ago',
    );
  });

  it('says so when the description is empty', () => {
    const empty = structuredClone(pr);
    empty.source.description = '';
    empty.source.descriptionHtml = '';
    show(empty, '#description');
    expect(root.querySelector('.desc-empty')!.textContent).toBe('No description provided.');
  });
});

describe('Commits tab', () => {
  it('lists commits oldest first with author, time and hash', async () => {
    await tab('Commits');
    const rows = [...root.querySelectorAll('.commit')];
    expect(rows.map((r) => r.querySelector('.commit-subject')!.textContent)).toEqual(
      local.source.commits.map((c) => c.subject),
    );
    expect(rows[0]!.querySelector('.commit-meta')!.textContent).toContain(
      'Bowi Fixtures committed 2 days ago',
    );
    expect(rows[0]!.querySelector('.sha .mono')!.textContent).toBe(
      local.source.commits[0]!.sha.slice(0, 7),
    );
    expect(text()).toContain('Oldest first.');
  });

  it('shows the full message behind the "…" button', async () => {
    const withBody = structuredClone(local);
    withBody.source.commits[0]!.body = 'Why this change was made.';
    show(withBody, '#commits');
    expect(root.querySelector('.commit-body')).toBeNull();
    await press(root.querySelector('.more'));
    expect(root.querySelector('.commit-body')!.textContent).toBe('Why this change was made.');
  });
});

describe('Changes tab', () => {
  beforeEach(() => show(local, '#changes'));
  const paths = () => [...root.querySelectorAll('.gh-path')].map((e) => e.textContent);

  it('lists files in GitHub order: folders before top-level files', () => {
    expect(paths()).toEqual([
      'src/auth/auth.controller.ts',
      'src/auth/auth.service.ts',
      'src/mail/mail.service.ts',
      'src/migrations/1730_add_email_verified.ts',
      'src/users/user.entity.ts',
      'src/utils/date.ts',
      'src/utils/helpers.ts',
      'src/utils/string.ts',
      'test/auth.service.spec.ts',
      'README.md',
      'package-lock.json',
    ]);
    const tree = [...root.querySelectorAll('.tree .tr')].map((e) => e.textContent);
    expect(tree.slice(0, 4)).toEqual(['src', 'auth', 'auth.controller.ts', 'auth.service.ts']);
    expect(tree.slice(-2)).toEqual(['README.md', 'package-lock.json']);
  });

  it('keeps generated files closed behind "Load diff"', async () => {
    const lock = root.querySelector('[aria-label="package-lock.json"]')!;
    expect(lock.textContent).toContain('Generated files are not rendered by default.');
    expect(lock.querySelectorAll('.ln')).toHaveLength(0);
    await press(lock.querySelector('.link-btn'));
    expect(lock.querySelectorAll('.ln').length).toBeGreaterThan(0);
  });

  it('switches between unified and split layouts', async () => {
    const service = () => root.querySelector('[aria-label="src/auth/auth.service.ts"]')!;
    expect(service().querySelectorAll('.ln').length).toBeGreaterThan(0);
    expect(service().querySelectorAll('.sr')).toHaveLength(0);
    await click('Split');
    expect(service().querySelectorAll('.ln')).toHaveLength(0);
    // The replaced import line sits next to its new version.
    const replaced = service().querySelector('.sr')!;
    expect(replaced.querySelector('.sd-d')!.textContent).toContain('Injectable, Unauthorized');
    expect(replaced.querySelector('.sd-a')!.textContent).toContain('BadRequestException');
  });

  it('filters the tree and the files', async () => {
    const input = root.querySelector('#file-filter') as HTMLInputElement;
    await act(() => {
      input.value = 'utils';
      input.dispatchEvent(new Event('input'));
    });
    expect(paths()).toEqual(['src/utils/date.ts', 'src/utils/helpers.ts', 'src/utils/string.ts']);
  });

  it('collapses and expands every file', async () => {
    await click('Collapse all');
    expect(root.querySelectorAll('.gh-file .ln')).toHaveLength(0);
    expect(text()).not.toContain('Load diff');
    await click('Expand all');
    expect(root.querySelectorAll('[aria-label="package-lock.json"] .ln').length).toBeGreaterThan(0);
  });
});
