import { describe, expect, it } from 'vitest';
import { createLayerResolver } from '../src/layers.ts';
import { createGeneratedMatcher, hasGeneratedHeader } from '../src/noise/generated.ts';
import { matchLines } from '../src/util/lcs.ts';

describe('generated files', () => {
  it('matches built-in patterns at any depth', () => {
    const m = createGeneratedMatcher([], null);
    expect(m.byPath('package-lock.json')).toBe('matches package-lock.json');
    expect(m.byPath('apps/web/yarn.lock')).toBe('matches yarn.lock');
    expect(m.byPath('packages/x/dist/index.js')).toBe('matches dist/**');
    expect(m.byPath('src/__snapshots__/a.test.ts.snap')).toBe('matches *.snap');
    expect(m.byPath('src/api.generated.ts')).toBe('matches *.generated.*');
    expect(m.byPath('src/distance.ts')).toBeNull();
  });

  it('uses configured patterns and .gitattributes, where later lines win', () => {
    const m = createGeneratedMatcher(
      ['src/graphql/generated/**'],
      '# comment\n*.pb.ts linguist-generated\nvendor/ linguist-generated=true\n/package-lock.json -linguist-generated\n',
    );
    expect(m.byPath('src/graphql/generated/types.ts')).toBe('matches src/graphql/generated/**');
    expect(m.byPath('proto/a.pb.ts')).toBe('.gitattributes linguist-generated');
    expect(m.byPath('vendor/lib/x.js')).toBe('.gitattributes linguist-generated');
    expect(m.byPath('package-lock.json')).toBeNull();
  });

  it('detects generator markers in the first lines only', () => {
    const marker = ['@gener', 'ated'].join('');
    expect(hasGeneratedHeader(`// ${marker} by protoc\nexport {};`)).toBe(true);
    expect(hasGeneratedHeader('// Code generated by x. DO NOT ' + 'EDIT.\n')).toBe(true);
    expect(hasGeneratedHeader(`${'\n'.repeat(10)}// ${marker}\n`)).toBe(false);
    expect(hasGeneratedHeader('export const a = 1;\n')).toBe(false);
  });
});

describe('layers', () => {
  it('assigns layers from path heuristics, tests and docs first', () => {
    const layer = createLayerResolver({});
    const cases: [string, string][] = [
      ['src/migrations/1730_x.ts', 'schema'],
      ['db/schema.sql', 'schema'],
      ['src/users/user.entity.ts', 'data'],
      ['src/models/user.ts', 'data'],
      ['src/mail/mail.service.ts', 'service'],
      ['src/auth/auth.controller.ts', 'api'],
      ['src/routes/users.ts', 'api'],
      ['src/components/Button.tsx', 'ui'],
      ['test/services/mail.ts', 'test'],
      ['src/auth/auth.service.spec.ts', 'test'],
      ['README.md', 'docs'],
      ['docs/setup.txt', 'docs'],
      ['package.json', 'config'],
      ['.github/workflows/ci.yml', 'config'],
      ['package-lock.json', 'config'],
      ['src/utils/date.ts', 'unknown'],
      ['packages/core/src/engine.ts', 'unknown'],
      ['packages/api/package.json', 'config'],
      ['src/domain/order.ts', 'domain'],
    ];
    expect(cases.map(([p]) => [p, layer(p)])).toEqual(cases);
  });

  it('lets configured globs win', () => {
    expect(createLayerResolver({ api: ['src/**/endpoints.ts'] })('src/x/endpoints.ts')).toBe('api');
    expect(createLayerResolver({ schema: ['db/**'] })('db/models/x.ts')).toBe('schema');
  });
});

describe('matchLines', () => {
  it('reports similarity and unmatched lines', () => {
    const r = matchLines(['a', 'b', 'c', 'd'], ['a', 'x', 'c', 'd']);
    expect(r.similarity).toBe(0.75);
    expect(r.unmatchedA).toEqual([1]);
    expect(r.unmatchedB).toEqual([1]);
    expect(matchLines([], []).similarity).toBe(1);
  });
});
